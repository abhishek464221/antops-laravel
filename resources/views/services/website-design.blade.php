$(document).ready(function () {
    $('#fpNewsletterForm').on('submit', function (e) {
        e.preventDefault();
        var $form = $(this);
        var $alert = $('#fpNewsletterAlert');
        $alert.text('').removeClass('fp-newsletter-success fp-newsletter-error');
        $.ajax({
            url: $form.attr('action'),
            type: 'POST',
            data: $form.serialize(),
            dataType: 'json',
            success: function (response) {
                $alert.addClass('fp-newsletter-success').text(response.message);
                $form[0].reset();
            },
            error: function (xhr) {
                var msg = 'Something went wrong. Please try again.';
                if (xhr.responseJSON && xhr.responseJSON.errors) {
                    msg = Object.values(xhr.responseJSON.errors).flat().join(' ');
                } else if (xhr.responseJSON && xhr.responseJSON.message) {
                    msg = xhr.responseJSON.message;
                }
                $alert.addClass('fp-newsletter-error').text(msg);
            }
        });
    });
});
